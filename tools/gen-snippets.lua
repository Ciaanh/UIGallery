-- gen-snippets.lua [ROOT] [--check]
--
-- Builds generated/Snippets.lua from the @snippet regions of the files UIGallery.toc loads, so the
-- code the gallery shows is the code that runs (the game cannot read its own files):
--
--   Lua:  -- @snippet <id>            XML:  <!-- @snippet <id> -->
--         ...                               ...
--         -- @end                           <!-- @end -->
--
-- Tabs become 4 spaces, common indentation is removed. A snippet may not contain "|" (WoW would
-- read it as an escape sequence in the code view). --check exits 1 when the committed file is
-- stale instead of writing it (tests/run.sh and the CI use it). Never shipped.
local root, check = ".", false
for _, a in ipairs(arg) do
    if a == "--check" then check = true else root = a end
end
root = root:gsub("\\", "/"):gsub("/+$", "")

local OUTPUT = "generated/Snippets.lua"

local function read(path)
    local f = io.open(root .. "/" .. path, "rb")
    if not f then return nil end
    local s = f:read("*a")
    f:close()
    return s
end

local errors = {}
local function fail(msg) errors[#errors + 1] = msg end

local MARKERS = {
    lua = { start = "^%s*%-%-%s*@snippet%s+([%w_%-]+)%s*$", stop = "^%s*%-%-%s*@end%s*$" },
    xml = { start = "^%s*<!%-%-%s*@snippet%s+([%w_%-]+)%s*%-%->%s*$", stop = "^%s*<!%-%-%s*@end%s*%-%->%s*$" },
}

local function Clean(lines)
    local out, minIndent = {}, nil
    for i, line in ipairs(lines) do
        line = line:gsub("\t", "    "):gsub("%s+$", "")
        out[i] = line
        if line ~= "" then
            local indent = #line:match("^ *")
            if not minIndent or indent < minIndent then minIndent = indent end
        end
    end
    for i, line in ipairs(out) do
        out[i] = line:sub((minIndent or 0) + 1)
    end
    while out[1] == "" do table.remove(out, 1) end
    while out[#out] == "" do table.remove(out) end
    return table.concat(out, "\n")
end

local snippets, order = {}, {}

local toc = read("UIGallery.toc")
if not toc then
    io.stderr:write("gen-snippets: cannot read " .. root .. "/UIGallery.toc\n")
    os.exit(1)
end

for entry in toc:gmatch("[^\r\n]+") do
    local path = entry:match("^%s*([^#%s].-)%s*$")
    local lang = path and path:match("%.(%a+)$")
    path = path and path:gsub("\\", "/")
    if path and MARKERS[lang] and path ~= OUTPUT then
        local text = read(path)
        if not text then
            fail(path .. ": listed in the toc but missing")
        else
            local marker, current, n = MARKERS[lang], nil, 0
            for line in (text .. "\n"):gmatch("([^\n]*)\n") do
                n = n + 1
                line = line:gsub("\r$", "")
                local id = line:match(marker.start)
                if id then
                    if current then
                        fail(("%s:%d: @snippet %s inside @snippet %s"):format(path, n, id, current.id))
                    end
                    current = { id = id, lang = lang, file = path, line = n, lines = {} }
                elseif line:match(marker.stop) then
                    if not current then
                        fail(("%s:%d: @end without @snippet"):format(path, n))
                    else
                        if snippets[current.id] then
                            fail(("%s:%d: duplicate snippet id %s (first in %s)"):format(
                                path, current.line, current.id, snippets[current.id].file))
                        end
                        current.code = Clean(current.lines)
                        if current.code == "" then
                            fail(("%s:%d: snippet %s is empty"):format(path, current.line, current.id))
                        end
                        if current.code:find("|", 1, true) then
                            fail(("%s:%d: snippet %s contains \"|\""):format(path, current.line, current.id))
                        end
                        snippets[current.id] = current
                        order[#order + 1] = current.id
                        current = nil
                    end
                elseif current then
                    current.lines[#current.lines + 1] = line
                end
            end
            if current then
                fail(("%s:%d: @snippet %s never closed"):format(path, current.line, current.id))
            end
        end
    end
end

if #errors > 0 then
    io.stderr:write(table.concat(errors, "\n") .. "\n")
    os.exit(1)
end

table.sort(order)

local function LongString(code)
    local level = 0
    while code:find("]" .. ("="):rep(level) .. "]", 1, true) do level = level + 1 end
    local eq = ("="):rep(level)
    return "[" .. eq .. "[\n" .. code .. "]" .. eq .. "]"
end

local out = {
    "-- GENERATED by tools/gen-snippets.lua from the @snippet regions of the files the toc loads.",
    "-- Do not edit: change the example file, then run  lua tools/gen-snippets.lua",
    "local _, ns = ...",
    "",
    "ns.Snippets = {",
}
for _, id in ipairs(order) do
    local s = snippets[id]
    out[#out + 1] = ("    [%q] = {"):format(id)
    out[#out + 1] = ("        lang = %q,"):format(s.lang)
    out[#out + 1] = ("        file = %q,"):format(s.file)
    out[#out + 1] = "        code = " .. LongString(s.code) .. ","
    out[#out + 1] = "    },"
end
out[#out + 1] = "}"
local generated = table.concat(out, "\n") .. "\n"

if check then
    local current = (read(OUTPUT) or ""):gsub("\r\n", "\n")
    if current ~= generated then
        io.stderr:write(OUTPUT .. " is stale: run  lua tools/gen-snippets.lua\n")
        os.exit(1)
    end
    print(("%d snippets, %s up to date"):format(#order, OUTPUT))
else
    local f = assert(io.open(root .. "/" .. OUTPUT, "wb"))
    f:write(generated)
    f:close()
    print(("%d snippets -> %s"):format(#order, OUTPUT))
end
